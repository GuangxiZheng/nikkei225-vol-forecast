def sq_dates():
    """SQ日 = 3/6/9/12月の第2金曜 (2016〜2027)。"""
    out = []
    for y in range(2016, 2028):
        for m in (3, 6, 9, 12):
            d = date(y, m, 1)
            fris = [d + timedelta(days=k) for k in range(1, 15)
                    if (d + timedelta(days=k)).weekday() == 4]
            out.append(fris[1].isoformat())
    return out


def main():
    df = build_features(load_data())
    df["y5"] = target_h(df, 5)

    # 窓 [T+1 .. T+5] に含まれるイベント日かでダミーを作る (金曜エントリのみ意味を持つ)
    events = {"nfp": [], "fomc": [], "boj": [], "sq": sq_dates()}
    for ds in pd.to_datetime(FOMC):
        nxt = ds + timedelta(days=1)  # 日本市場の反応日 (翌朝)
        events["fomc"].append(nxt.isoformat())
    events["boj"] = list(BOJ)
    first_fri = {}
    for ds in pd.date_range("2015-01-01", "2027-12-31"):
        if ds.weekday() == 4:
            key = (ds.year, ds.month)
            first_fri.setdefault(key, ds.isoformat())
    events["nfp"] = list(first_fri.values())  # 影響はその翌営業日の窓で捉える
    ev_sets = {k: set(v) for k, v in events.items()}

    dates = df["date"].dt.strftime("%Y-%m-%d").to_numpy()
    for name in events:
        col = np.zeros(len(df), dtype=float)
        for i in range(len(df) - 5):
            window = set(dates[i + 1:i + 6])
            if window & ev_sets[name]:
                col[i] = 1.0
        df[f"{name}_ahead"] = col

    variants = {
        "C1 基準 (v2.1)": COLS,
        "C2 +nfp_ahead": COLS + ["nfp_ahead"],
        "C3 +fomc_ahead": COLS + ["fomc_ahead"],
        "C4 +boj_ahead": COLS + ["boj_ahead"],
        "C5 +sq_ahead": COLS + ["sq_ahead"],
        "C6 イベント4つ全部": COLS + ["nfp_ahead", "fomc_ahead", "boj_ahead", "sq_ahead"],
    }
    res, detail = evaluate(df, variants, base_tag="C1 基準 (v2.1)")

    lines = [
        "# 特徴量拡張検証レポート3 (優先順位3: イベントダミー)",
        "",
        f"実行: {pd.Timestamp.now():%Y-%m-%d %H:%M} ／ 評価: 2018-01-01 以降の金曜"
        "・ベンチマーク=週次RV。基準は v2.1。",
        "ダミーは線形加算 (ボラ水準へのシフトとして効く) — 乗算的な增幅は別途。",
        "FOMC・日銀の日付表は公開スケジュールの手編集 (臨時会合等の誤差があり得る)。",
        "",
        "## 結果",
        "",
        "| バリアント | 特徴量数 | n | OOS R² (全期間) | 前半 | 後半 |"
        " ΔMSE vs 基準 (95%CI) |",
        "|---|---|---|---|---|---|---|",
    ]
    for _, x in res.iterrows():
        d = x["dmse"]
        ci_s = (f"{d:+.1f} ± {x['ci']:.1f}"
                f"{' ✅基準より有意に小さい' if d - x['ci'] > 0 else ''}")
        lines.append(f"| {x['tag']} | {x['k']} | {x['n']} | {x['r2']:+.3f} | "
                     f"{x['r2_1']:+.3f} | {x['r2_2']:+.3f} | {ci_s} |")
    lines += ["", "## 採用判定 (後半改善 / CI除外ゼロ / 前半同方向)", ""]
    adopted = []
    for _, x in res.iterrows():
        if x["tag"].startswith("C1"):
            continue
        ok1 = x["r2_2"] > res.loc[0, "r2_2"]
        ok2 = x["dmse"] - x["ci"] > 0
        ok3 = x["r2_1"] > res.loc[0, "r2_1"] * 0.98
        verdict = "採用候補" if (ok1 and ok2 and ok3) else "不採用"
        if ok1 and ok2 and ok3:
            adopted.append(x["tag"])
        lines.append(f"- **{x['tag']}**: 後半改善 {ok1} / CI除外ゼロ {ok2} / "
                     f"前半同方向 {ok3} → **{verdict}**")
    lines += ["", "## 制限", "",
              "- ダミーは窓内イベントの有無のみ (イベントの大きさ・結果の方向は未反映)。",
              "- 6バリアントの多重検定は厳密には補正していない。", ""]
    REPORT.write_text("\n".join(lines) + "\n")

    print(res.to_string(index=False,
                        formatters={"r2": "{:+.3f}".format, "r2_1": "{:+.3f}".format,
                                    "r2_2": "{:+.3f}".format,
                                    "dmse": "{:+.1f}".format, "ci": "±{:.1f}".format}))
    print(f"\n採用候補: {adopted if adopted else 'なし'}")
    print(f"saved: {REPORT}")


if __name__ == "__main__":
    main()
